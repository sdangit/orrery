"""Fit camera depth to measured V886 outline without changing orbital elements.

Run with Python + NumPy/SciPy. Geometry is generated by the shared JS solver.
Body anchors fix separate horizontal/vertical scales and translation in a top
view. This allows the capture's ~4% axis-scale difference; it does NOT prove
whether that difference is capture scaling, game projection or slight camera
tilt. Only inverse camera distance is fitted against the orbit. Alternate
samples are withheld to check the rest of the curve. Those samples share the
same screenshot, so they are not independent physical observations.
"""
import json, subprocess
from pathlib import Path
import numpy as np
from scipy.optimize import least_squares
root = Path(__file__).resolve().parent
image = json.loads((root/'fixtures/v886-camera-image-points.json').read_text())
g = json.loads(subprocess.check_output(['node',str(root/'v886-camera-geometry.mjs')]))
bodies, orbit = np.array(g['bodies']), np.array(g['orbit'])
observed = np.array([b['point'] for b in image['bodyCentres']])
# Axis-aligned top view; do not fit shear or tilt to nearly coplanar anchors.
sx,cx = np.linalg.lstsq(np.c_[bodies[:,0],np.ones(len(bodies))],observed[:,0],rcond=None)[0]
sy,cy = np.linalg.lstsq(np.c_[-bodies[:,1],np.ones(len(bodies))],observed[:,1],rcond=None)[0]
points = np.array(image['outlinePoints'])
def project(x,k):
    return x[:,:2]*[sx,-sy]/(1-k*x[:,2:])+[cx,cy]
def distances(k):
    curve=project(orbit,k);a=curve[:-1];v=np.diff(curve,axis=0)
    t=np.clip(np.sum((points[:,None,:]-a)*v,axis=2)/np.sum(v*v,axis=1),0,1)
    return np.linalg.norm(a+t[:,:,None]*v-points[:,None,:],axis=2).min(axis=1)
def rms(x): return float(np.sqrt(np.mean(x*x)))
fit=least_squares(lambda p:distances(p[0])[::2],[.01],bounds=([0],[.1]),diff_step=1e-4)
k=float(fit.x[0]); h=image['previewHeight']
fixed=[]
for fov in [15,55]:
    depth=sy*2*np.tan(np.radians(fov)/2)/h
    errors=distances(depth)
    fixed.append(dict(verticalFovDeg=fov,inverseDistancePerAU=depth,rmsPreviewPx=rms(errors),maxPreviewPx=float(errors.max())))
result=dict(description=__doc__,camera=dict(scaleX=sx,scaleY=sy,centre=[cx,cy],inverseDistancePerAU=k,
    inferredVerticalFovDeg=float(np.degrees(2*np.arctan(h*k/(2*sy))))),
    innerBodyRmsPreviewPx=rms(np.linalg.norm(project(bodies,k)-observed,axis=1)),
    fitSampleIndices=list(range(0,len(points),2)),holdoutIndices=list(range(1,len(points),2)),
    trainRmsPreviewPx=rms(distances(k)[::2]),holdoutRmsPreviewPx=rms(distances(k)[1::2]),
    orthographicRmsPreviewPx=rms(distances(0)),fixedFovComparisons=fixed,
    limitations=['Near-top, centred camera assumed; slight tilt and image scaling remain partly degenerate.',
    'FOV inferred from this full game viewport, not from settings or an official specification.',
    'Body 10 outline estimates perspective; it is not independent validation of every orbital parameter.',
    'App screenshot shows 55-degree camera from code; no independent app camera fit claimed.',
    'This local camera result does not establish orbital-to-galactic alignment.'])
print(json.dumps(result,indent=2))
